"""Deterministic mock provider for CI and offline runs."""

from __future__ import annotations

import asyncio
import json
import time
from typing import Any

from app.ai.errors import ProviderError, ProviderErrorCode
from app.ai.protocol import DocGenProvider
from app.ai.types import (
    CompleteRequest,
    CompleteResponse,
    ModelInfo,
    ProviderKind,
    TestResult,
)


class MockProvider(DocGenProvider):
    adapter_type = "mock"
    kind = ProviderKind.MODEL
    name = "mock"

    def __init__(
        self,
        *,
        delay_seconds: float = 0.0,
        fail_with: ProviderErrorCode | None = None,
        models: list[str] | None = None,
    ) -> None:
        self.delay_seconds = delay_seconds
        self.fail_with = fail_with
        self._models = models or ["mock-model"]
        self._cancelled = False
        self._tasks: set[asyncio.Task[Any]] = set()

    async def complete(self, request: CompleteRequest) -> CompleteResponse:
        self._cancelled = False
        if self.fail_with is not None:
            raise ProviderError(self.fail_with, f"Mock failure: {self.fail_with.value}")
        delay = self.delay_seconds
        if request.timeout_seconds is not None and self.delay_seconds > request.timeout_seconds:
            await asyncio.sleep(request.timeout_seconds)
            raise ProviderError(ProviderErrorCode.TIMEOUT, "Mock timed out", retryable=True)
        if delay:
            task = asyncio.create_task(asyncio.sleep(delay))
            self._tasks.add(task)
            try:
                await task
            except asyncio.CancelledError as exc:
                raise ProviderError(
                    ProviderErrorCode.TIMEOUT,
                    "Mock cancelled",
                    retryable=True,
                ) from exc
            finally:
                self._tasks.discard(task)
        if self._cancelled:
            raise ProviderError(ProviderErrorCode.TIMEOUT, "Mock cancelled", retryable=True)

        section_id = "section"
        marker = "section_id="
        user = request.user
        if marker in user:
            start = user.index(marker) + len(marker)
            section_id = user[start:].split(None, 1)[0].strip("'\"")
        follow_up = "Follow-up instruction from the editor" in user
        suggest = "Suggest an improved version" in user
        suffix = ""
        if follow_up:
            fingerprint = abs(hash(user)) % 10_000_000
            suffix = f" [follow-up:{fingerprint}]"
        elif suggest:
            suffix = " [suggestion]"
        summary = (
            f"Auto-generated overview for {section_id} from repository analysis.{suffix}"
        )
        payload: dict[str, Any] = {
            "title": section_id.replace("_", " ").title(),
            "summary": summary,
            "bullets": [
                "Derived from file tree and language summary",
                "Symbols and structure considered",
                "Secrets redacted before prompting",
                *([f"Follow-up applied for {section_id}"] if follow_up else []),
                *(["Suggestion draft"] if suggest and not follow_up else []),
            ],
            "code_refs": [],
            "notes": "Generated by MockProvider" + (" (follow-up)" if follow_up else ""),
            "citations": [],
        }
        text: str = json.dumps(payload) if request.response_json else summary
        return CompleteResponse(text=text, model=self._models[0], usage={"prompt_tokens": 1})

    async def list_models(self) -> list[ModelInfo]:
        return [ModelInfo(id=m, name=m, owned_by="mock") for m in self._models]

    async def test_connection(self) -> TestResult:
        started = time.perf_counter()
        if self.fail_with is not None:
            return TestResult(
                ok=False,
                latency_ms=(time.perf_counter() - started) * 1000,
                message=f"Mock failure: {self.fail_with.value}",
            )
        return TestResult(
            ok=True,
            latency_ms=(time.perf_counter() - started) * 1000,
            message="Mock provider ready",
            models_sample=list(self._models),
        )

    async def cancel(self, handle: Any | None = None) -> None:
        self._cancelled = True
        for task in list(self._tasks):
            task.cancel()
