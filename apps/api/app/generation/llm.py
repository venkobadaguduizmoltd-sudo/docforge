"""OpenAI-compatible LLM client (Ollama) + deterministic mock for tests."""

from __future__ import annotations

import json
import logging
from typing import Any, Protocol

import httpx

from app.core.config import get_settings

logger = logging.getLogger("docforge.generation.llm")


class LLMClient(Protocol):
    async def complete_json(self, *, system: str, user: str) -> dict[str, Any]: ...


class MockLLMClient:
    """Deterministic content for CI and offline runs."""

    async def complete_json(self, *, system: str, user: str) -> dict[str, Any]:
        # Extract section_id from prompt when present
        section_id = "section"
        marker = "section_id="
        if marker in user:
            start = user.index(marker) + len(marker)
            rest = user[start:]
            section_id = rest.split(None, 1)[0].strip("'\"")
        return {
            "title": section_id.replace("_", " ").title(),
            "summary": f"Auto-generated overview for {section_id} from repository analysis.",
            "bullets": [
                "Derived from file tree and language summary",
                "Symbols and structure considered",
                "Secrets redacted before prompting",
            ],
            "code_refs": [],
            "notes": "Generated by MockLLMClient",
        }


class OpenAICompatibleClient:
    """Chat completions against an OpenAI-compatible endpoint (e.g. Ollama)."""

    def __init__(
        self,
        base_url: str,
        model: str,
        api_key: str = "ollama",
        *,
        client: httpx.AsyncClient | None = None,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.model = model
        self.api_key = api_key
        self._client = client
        self._owns = client is None

    async def _http(self) -> httpx.AsyncClient:
        if self._client is None:
            self._client = httpx.AsyncClient(timeout=120.0)
        return self._client

    async def aclose(self) -> None:
        if self._owns and self._client is not None:
            await self._client.aclose()
            self._client = None

    async def complete_json(self, *, system: str, user: str) -> dict[str, Any]:
        client = await self._http()
        url = f"{self.base_url}/v1/chat/completions"
        response = await client.post(
            url,
            headers={"Authorization": f"Bearer {self.api_key}"},
            json={
                "model": self.model,
                "messages": [
                    {"role": "system", "content": system},
                    {"role": "user", "content": user},
                ],
                "temperature": 0.2,
                "response_format": {"type": "json_object"},
            },
        )
        if response.status_code >= 400:
            # Some Ollama builds ignore response_format — retry without it
            response = await client.post(
                url,
                headers={"Authorization": f"Bearer {self.api_key}"},
                json={
                    "model": self.model,
                    "messages": [
                        {"role": "system", "content": system},
                        {
                            "role": "user",
                            "content": user + "\nRespond with JSON only.",
                        },
                    ],
                    "temperature": 0.2,
                },
            )
        response.raise_for_status()
        data = response.json()
        content = data["choices"][0]["message"]["content"]
        return _parse_json_content(content)


def _parse_json_content(content: str) -> dict[str, Any]:
    content = content.strip()
    if content.startswith("```"):
        lines = content.splitlines()
        lines = [ln for ln in lines if not ln.startswith("```")]
        content = "\n".join(lines)
    return json.loads(content)


def get_llm_client() -> LLMClient:
    settings = get_settings()
    provider = settings.llm_provider.lower()
    if provider in {"mock", "fixture", "test"}:
        return MockLLMClient()
    return OpenAICompatibleClient(
        base_url=settings.ollama_base_url,
        model=settings.llm_model,
        api_key=settings.llm_api_key,
    )
